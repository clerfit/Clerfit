const { test, expect } = require('@playwright/test');
const AxeBuilder = require('@axe-core/playwright').default;
test('WHtR works with units, boundaries, reset and mobile layout', async ({page}) => {
  await page.setViewportSize({width:390,height:844});
  const pageErrors=[]; const localFailures=[];
  page.on('pageerror',e=>pageErrors.push(e.message));
  page.on('response',r=>{if(r.url().startsWith('http://127.0.0.1:8000/')&&r.status()>=400)localFailures.push(r.status()+' '+r.url());});
  await page.goto('http://127.0.0.1:8000/html/wht.html',{waitUntil:'networkidle'});
  await expect(page.locator('#waist')).toBeVisible();
  await expect(page.locator('#height')).toBeVisible();
  await expect(page.getByRole('button',{name:'Calculate WHtR'})).toBeVisible();
  await expect(page.getByRole('button',{name:'Reset'})).toBeVisible();
  await expect(page.getByRole('main')).toHaveCount(1);
  await page.locator('#waist').fill('80'); await page.locator('#height').fill('180');
  await page.getByRole('button',{name:'Calculate WHtR'}).click();
  await expect(page.locator('#result')).toContainText('0.444');
  await expect(page.locator('#formula')).toContainText('80.0 cm');
  await page.locator('#waistUnit').selectOption('in');
  await expect.poll(async()=>Number(await page.locator('#waist').inputValue())).toBeCloseTo(31.4961,3);
  await expect(page.locator('#waist')).toHaveAttribute('min','7.87401575');
  await page.locator('#heightUnit').selectOption('ft');
  await expect.poll(async()=>Number(await page.locator('#height').inputValue())).toBeCloseTo(5.9055,3);
  await expect(page.locator('#height')).toHaveAttribute('min','1.64041995');
  await page.getByRole('button',{name:'Calculate WHtR'}).click();
  await expect(page.locator('#result')).toContainText('0.444');
  await page.locator('#waistUnit').selectOption('cm');
  await page.locator('#heightUnit').selectOption('cm');
  await page.locator('#waist').fill('19.9');
  await page.getByRole('button',{name:'Calculate WHtR'}).click();
  await expect(page.locator('.clerfit-input-error').first()).toBeVisible();
  await expect(page.locator('#result')).not.toContainText('0.444');
  await page.getByRole('button',{name:'Reset'}).click();
  await expect(page.locator('#waist')).toHaveValue('');
  await expect(page.locator('#height')).toHaveValue('');
  await expect(page.locator('#result')).toBeEmpty();
  await expect(page.locator('#formula')).toBeEmpty();
  await expect(page.locator('#waist')).toHaveAttribute('min','20');
  await expect(page.locator('#height')).toHaveAttribute('min','50');
  await expect(page.locator('#waist')).toBeFocused();
  await page.keyboard.press('Tab');
  expect(parseFloat(await page.locator('#waistUnit').evaluate(el=>getComputedStyle(el).outlineWidth))).toBeGreaterThanOrEqual(3);
  await expect(page.getByRole('link',{name:/Go to ClerFit home/i})).toBeVisible();
  await expect(page.getByRole('link',{name:/Contact Us at ClerFit/i})).toBeVisible();
  let dims=await page.evaluate(()=>({viewport:document.documentElement.clientWidth,doc:document.documentElement.scrollWidth}));
  expect(dims.doc).toBeLessThanOrEqual(dims.viewport);
  await page.setViewportSize({width:320,height:844});
  dims=await page.evaluate(()=>({viewport:document.documentElement.clientWidth,doc:document.documentElement.scrollWidth}));
  expect(dims.doc).toBeLessThanOrEqual(dims.viewport);
  expect(pageErrors).toEqual([]); expect(localFailures).toEqual([]);
});
test('WHtR page has no automated axe accessibility violations',async({page})=>{
  await page.setViewportSize({width:390,height:844});
  await page.goto('http://127.0.0.1:8000/html/wht.html',{waitUntil:'networkidle'});
  const results=await new AxeBuilder({page}).analyze();
  expect(results.violations.map(v=>({id:v.id,impact:v.impact,nodes:v.nodes.map(n=>n.target)}))).toEqual([]);
});
